"""Airports beyond the nine hand-checked ones, from the OpenFlights airport database (ODbL).

    python pipeline/airport_db.py --update

Downloads airports.dat from OpenFlights (once, into pipeline/raw/) and writes pipeline/airports_extra.json
with only the airports that confirmed observed routes need (pipeline/observed_routes.json). Each airport
keeps its IATA code, name, city, coordinates (rounded to 4 decimals) and IANA time zone.
Source: https://openflights.org/data (ODbL), coordinates and time zones from OurAirports.
"""
from __future__ import annotations

import argparse
import csv
import json
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
OPENFLIGHTS = "https://raw.githubusercontent.com/jpatokal/openflights/master/data/airports.dat"
RAW = HERE / "raw" / "openflights" / "airports.dat"
EXTRA = HERE / "airports_extra.json"
OBSERVED = HERE / "observed_routes.json"
ABOUT = "Airports for observed JetBlue routes, from OpenFlights (openflights.org/data, ODbL). Generated by airport_db.py."


def _short(name: str) -> str:
    return name.removesuffix(" Airport").strip()


def read_openflights(path: Path = RAW) -> dict[str, dict]:
    out: dict[str, dict] = {}
    with path.open(encoding="utf-8") as fh:
        for row in csv.reader(fh):
            # id, name, city, country, IATA, ICAO, lat, lon, alt, utc offset, dst, tz, type, source
            if len(row) < 12 or not row[4] or row[4] == r"\N" or row[11] in ("", r"\N"):
                continue
            out[row[4]] = {"name": _short(row[1]), "city": row[2], "country": row[3],
                           "lat": round(float(row[6]), 4), "lon": round(float(row[7]), 4), "tz": row[11]}
    return out


def confirmed_codes(observed: dict) -> set[str]:
    return {c for r in observed.get("routes", {}).values() if r.get("confirmed") for c in (r["origin"], r["dest"])}


def update(core: set[str]) -> int:
    if not RAW.exists():
        RAW.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(OPENFLIGHTS, RAW)
    db = read_openflights()
    observed = json.loads(OBSERVED.read_text()) if OBSERVED.exists() else {}
    needed = sorted(confirmed_codes(observed) - core)
    airports = {c: db[c] for c in needed if c in db}
    missing = [c for c in needed if c not in db]
    EXTRA.write_text(json.dumps({"about": ABOUT, "missing": missing, "airports": airports}, indent=1, ensure_ascii=False) + "\n")
    print(f"{len(airports)} airports written to {EXTRA.name}" + (f"; not in OpenFlights: {', '.join(missing)}" if missing else ""))
    return len(airports)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--update", action="store_true")
    if ap.parse_args().update:
        from airports import CORE_AIRPORTS
        update(set(CORE_AIRPORTS))
