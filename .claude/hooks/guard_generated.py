#!/usr/bin/env python3
"""PreToolUse hook: block hand edits to files the pipeline generates.

Generated data must change by changing the pipeline and re-running it, otherwise the site and
the engine drift apart. Exit 2 blocks the Edit/Write and tells Claude why.
"""
import json
import sys

GENERATED = (
    "web/public/data/routes/",
    "web/public/data/routes.json",
    "web/public/data/insights.json",
    "web/public/data/basemap.json",
    "web/public/data/evaluation.json",
    "web/lib/engine/fixtures/golden.json",
)

event = json.load(sys.stdin)
path = (event.get("tool_input") or {}).get("file_path", "").replace("\\", "/")
if any(g in path for g in GENERATED):
    print(
        f"{path} is generated by the pipeline. Change pipeline/*.py and run "
        "`python pipeline/build_data.py` (or stats.py / basemap.py / evaluate.py) instead of editing it.",
        file=sys.stderr,
    )
    sys.exit(2)
sys.exit(0)
